//! Types and schemas for tool definitions, function calls, and model outputs.

use serde::{Deserialize, Serialize};

/// Definition of an external tool provided to the language model.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ToolDefinition {
    /// Type of tool, typically `"function"`.
    #[serde(rename = "type")]
    pub tool_type: String,
    /// Function specification for this tool.
    pub function: FunctionDefinition,
}

impl ToolDefinition {
    /// Constructs a new function tool definition with name, description, and parameter schema.
    pub fn new_function(
        name: impl Into<String>,
        description: Option<String>,
        parameters: serde_json::Value,
    ) -> Self {
        Self {
            tool_type: "function".to_string(),
            function: FunctionDefinition {
                name: name.into(),
                description,
                parameters,
            },
        }
    }
}

/// Detailed specification for a callable function tool.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FunctionDefinition {
    /// Unique name of the function.
    pub name: String,
    /// Optional human-readable description explaining function purpose.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    /// JSON Schema describing expected parameters.
    #[serde(default)]
    pub parameters: serde_json::Value,
}

/// Parsed representation of an internal tool call extracted from model output.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ParsedToolCall {
    /// Unique call identifier.
    pub id: String,
    /// Name of the function being invoked.
    pub name: String,
    /// Parsed JSON arguments object or value.
    pub arguments: serde_json::Value,
}

impl ParsedToolCall {
    /// Creates a new parsed tool call.
    pub fn new(
        id: impl Into<String>,
        name: impl Into<String>,
        arguments: serde_json::Value,
    ) -> Self {
        Self {
            id: id.into(),
            name: name.into(),
            arguments,
        }
    }

    /// Converts this parsed call into OpenAI wire format with stringified JSON arguments.
    pub fn to_openai(&self) -> OpenAiToolCall {
        let arguments_str =
            serde_json::to_string(&self.arguments).unwrap_or_else(|_| "{}".to_string());
        OpenAiToolCall {
            id: self.id.clone(),
            call_type: "function".to_string(),
            function: OpenAiFunctionCall {
                name: self.name.clone(),
                arguments: arguments_str,
            },
        }
    }
}

/// Tool call representation matching the OpenAI Chat Completion API wire schema.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OpenAiToolCall {
    /// Call identifier.
    pub id: String,
    /// Type discriminator, fixed to `"function"`.
    #[serde(rename = "type")]
    pub call_type: String,
    /// Function call details.
    pub function: OpenAiFunctionCall,
}

/// Function invocation payload in OpenAI wire schema.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OpenAiFunctionCall {
    /// Name of function called.
    pub name: String,
    /// JSON string of arguments.
    pub arguments: String,
}

/// Disjoint output resulting from model completion: either plain assistant text or tool calls.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum ModelOutput {
    /// Plain text generated by the model.
    Text(String),
    /// One or more structured tool calls requested by the model.
    ToolCalls(Vec<ParsedToolCall>),
}
