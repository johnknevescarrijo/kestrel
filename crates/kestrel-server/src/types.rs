/// Represents a single model descriptor in OpenAI models listing.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ModelObject {
    /// Model identifier.
    pub id: String,
    /// Object kind, fixed to "model".
    pub object: String,
    /// Creation timestamp (unix epoch seconds).
    pub created: u64,
    /// Entity owning the model.
    pub owned_by: String,
}

/// Response returned by `GET /v1/models`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ModelListResponse {
    /// Object kind, fixed to "list".
    pub object: String,
    /// List of available model objects.
    pub data: Vec<ModelObject>,
}

/// A single message in a chat completion conversation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChatMessage {
    /// Role of the message sender (e.g. "system", "user", "assistant").
    pub role: String,
    /// Message content string.
    #[serde(default)]
    pub content: String,
    /// Structured tool calls generated by assistant.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<OpenAiToolCall>>,
}

impl ChatMessage {
    /// Constructs a message with role and content.
    pub fn new(role: impl Into<String>, content: impl Into<String>) -> Self {
        Self {
            role: role.into(),
            content: content.into(),
            tool_calls: None,
        }
    }
    /// Constructs a user message.
    pub fn user(content: impl Into<String>) -> Self {
        Self::new("user", content)
    }
    /// Constructs a system message.
    pub fn system(content: impl Into<String>) -> Self {
        Self::new("system", content)
    }
    /// Constructs an assistant message.
    pub fn assistant(content: impl Into<String>) -> Self {
        Self::new("assistant", content)
    }
}

impl Default for ChatMessage {
    fn default() -> Self {
        Self {
            role: "user".to_string(),
            content: String::new(),
            tool_calls: None,
        }
    }
}

/// Response format specification for structured output (JSON mode or JSON Schema).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ResponseFormat {
    /// Format type: "text", "json_object", or "json_schema".
    #[serde(rename = "type")]
    pub format_type: String,
    /// Optional JSON Schema configuration when type is "json_schema".
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub json_schema: Option<JsonSchemaConfig>,
}

/// JSON Schema configuration for structured output.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct JsonSchemaConfig {
    /// Schema identifier name.
    pub name: String,
    /// Optional description.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    /// Raw JSON Schema definition.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub schema: Option<serde_json::Value>,
    /// Whether strict validation is requested.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub strict: Option<bool>,
}

/// Request body for `POST /v1/chat/completions`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ChatCompletionRequest {
    /// Target model identifier.
    pub model: String,
    /// Conversation messages history.
    pub messages: Vec<ChatMessage>,
    /// Optional limit on the number of generated tokens.
    #[serde(default)]
    pub max_tokens: Option<usize>,
    /// Whether to stream partial message deltas via Server-Sent Events.
    #[serde(default)]
    pub stream: Option<bool>,
    /// Sampling temperature (optional).
    #[serde(default)]
    pub temperature: Option<f32>,
    /// Optional user/session identifier.
    #[serde(default)]
    pub user: Option<String>,
    /// Explicit Kestrel session identifier override.
    #[serde(default)]
    pub session_id: Option<String>,
    /// Available tools definitions.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tools: Option<Vec<ToolDefinition>>,
    /// Directives controlling tool execution ("none", "auto", "required", or object).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_choice: Option<serde_json::Value>,
    /// Override for maximum tool retries upon validation failure.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_tool_retries: Option<usize>,
    /// Optional response format for structured output ("text", "json_object", "json_schema").
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub response_format: Option<ResponseFormat>,
}

impl Default for ChatCompletionRequest {
    fn default() -> Self {
        Self {
            model: "default".to_string(),
            messages: Vec::new(),
            max_tokens: None,
            stream: None,
            temperature: None,
            user: None,
            session_id: None,
            tools: None,
            tool_choice: None,
            max_tool_retries: None,
            response_format: None,
        }
    }
}

