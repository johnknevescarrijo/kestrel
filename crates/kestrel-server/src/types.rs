/// Input payload for `POST /v1/embeddings` (single string or array of strings).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum EmbeddingInput {
    /// Single text string.
    Single(String),
    /// Batch of text strings.
    Multiple(Vec<String>),
}

/// Request body for `POST /v1/embeddings`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct EmbeddingRequest {
    /// Target model identifier.
    pub model: String,
    /// Input text(s) to embed.
    pub input: EmbeddingInput,
    /// Optional encoding format ("float" by default).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub encoding_format: Option<String>,
    /// Optional output vector dimension override.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub dimensions: Option<usize>,
}

/// Single embedding vector entry in response.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct EmbeddingObject {
    /// Object type, fixed to "embedding".
    pub object: String,
    /// Floating-point embedding vector.
    pub embedding: Vec<f32>,
    /// Position index in the input list.
    pub index: usize,
}

/// Token usage statistics for an embedding request.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct EmbeddingUsage {
    /// Number of prompt tokens processed.
    pub prompt_tokens: usize,
    /// Total tokens processed.
    pub total_tokens: usize,
}

/// Response returned by `POST /v1/embeddings`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct EmbeddingResponse {
    /// Object type, fixed to "list".
    pub object: String,
    /// List of generated embedding objects.
    pub data: Vec<EmbeddingObject>,
    /// Model used for generating embeddings.
    pub model: String,
    /// Token usage statistics.
    pub usage: EmbeddingUsage,
}

/// Token usage metrics for a completion request.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Usage {
    /// Tokens processed in prompt/prefill.
    pub prompt_tokens: usize,
    /// Tokens generated by the model.
    pub completion_tokens: usize,
    /// Total tokens evaluated.
    pub total_tokens: usize,
}

/// Choice entry in non-streaming chat completion response.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChatChoice {
    /// Index of this choice in response list.
    pub index: usize,
    /// Generated assistant message.
    pub message: ChatMessage,
    /// Reason why completion stopped (e.g. "stop", "length").
    pub finish_reason: Option<String>,
}

/// Response returned by non-streaming `POST /v1/chat/completions`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChatCompletionResponse {
    /// Unique completion identifier.
    pub id: String,
    /// Object kind, fixed to "chat.completion".
    pub object: String,
    /// Unix timestamp when completion was generated.
    pub created: u64,
    /// Model name used for generation.
    pub model: String,
    /// Generated choices.
    pub choices: Vec<ChatChoice>,
    /// Token usage statistics.
    pub usage: Usage,
}

/// Delta payload for SSE streaming chunks.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
