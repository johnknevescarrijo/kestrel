//! OpenAI-compatible API types and Kestrel session management types.

use kestrel_core::session::SessionMetadata;
use kestrel_tools::{format_tools_prompt, OpenAiToolCall, ToolDefinition};
use serde::{Deserialize, Serialize};

/// Represents a single model descriptor in OpenAI models listing.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ModelObject {
    /// Model identifier.
    pub id: String,
    /// Object kind, fixed to "model".
    pub object: String,
    /// Creation timestamp (unix epoch seconds).
    pub created: u64,
    /// Entity owning the model.
    pub owned_by: String,
}

/// Response returned by `GET /v1/models`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ModelListResponse {
    /// Object kind, fixed to "list".
    pub object: String,
    /// List of available model objects.
    pub data: Vec<ModelObject>,
}

/// A single message in a chat completion conversation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChatMessage {
    /// Role of the message sender (e.g. "system", "user", "assistant").
    pub role: String,
    /// Message content string.
    #[serde(default)]
    pub content: String,
    /// Structured tool calls generated by assistant.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<OpenAiToolCall>>,
}

impl ChatMessage {
    /// Constructs a message with role and content.
    pub fn new(role: impl Into<String>, content: impl Into<String>) -> Self {
        Self {
            role: role.into(),
            content: content.into(),
            tool_calls: None,
        }
    }

    /// Constructs a user message.
    pub fn user(content: impl Into<String>) -> Self {
        Self::new("user", content)
    }

    /// Constructs a system message.
    pub fn system(content: impl Into<String>) -> Self {
        Self::new("system", content)
    }

    /// Constructs an assistant message.
    pub fn assistant(content: impl Into<String>) -> Self {
        Self::new("assistant", content)
    }
}

impl Default for ChatMessage {
    fn default() -> Self {
        Self {
            role: "user".to_string(),
            content: String::new(),
            tool_calls: None,
        }
    }
}

/// Request body for `POST /v1/chat/completions`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ChatCompletionRequest {
    /// Target model identifier.
    pub model: String,
    /// Conversation messages history.
    pub messages: Vec<ChatMessage>,
    /// Optional limit on the number of generated tokens.
    #[serde(default)]
    pub max_tokens: Option<usize>,
    /// Whether to stream partial message deltas via Server-Sent Events.
    #[serde(default)]
    pub stream: Option<bool>,
    /// Sampling temperature (optional).
    #[serde(default)]
    pub temperature: Option<f32>,
    /// Optional user/session identifier.
    #[serde(default)]
    pub user: Option<String>,
    /// Explicit Kestrel session identifier override.
    #[serde(default)]
    pub session_id: Option<String>,
    /// Available tools definitions.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tools: Option<Vec<ToolDefinition>>,
    /// Directives controlling tool execution ("none", "auto", "required", or object).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_choice: Option<serde_json::Value>,
    /// Override for maximum tool retries upon validation failure.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_tool_retries: Option<usize>,
}

impl Default for ChatCompletionRequest {
    fn default() -> Self {
        Self {
            model: "default".to_string(),
            messages: Vec::new(),
            max_tokens: None,
            stream: None,
            temperature: None,
            user: None,
            session_id: None,
            tools: None,
            tool_choice: None,
            max_tool_retries: None,
        }
    }
}

/// Formats a series of chat messages into a ChatML prompt template.
pub fn format_chatml_prompt(messages: &[ChatMessage]) -> String {
    format_chatml_prompt_with_tools(messages, None)
}

/// Formats chat messages and optionally injects tool definitions into the ChatML prompt.
pub fn format_chatml_prompt_with_tools(
    messages: &[ChatMessage],
    tools: Option<&[ToolDefinition]>,
) -> String {
    let mut prompt = String::new();
    let has_system = messages.iter().any(|m| m.role == "system");

    if let Some(tool_list) = tools {
        if !tool_list.is_empty() && !has_system {
            prompt.push_str("<|im_start|>system\n");
            prompt.push_str(&format_tools_prompt(tool_list));
            prompt.push_str("<|im_end|>\n");
        }
    }

    for msg in messages {
        prompt.push_str("<|im_start|>");
        prompt.push_str(&msg.role);
        prompt.push('\n');
        prompt.push_str(&msg.content);
        if msg.role == "system" {
            if let Some(tool_list) = tools {
                if !tool_list.is_empty() {
                    prompt.push_str("\n\n");
                    prompt.push_str(&format_tools_prompt(tool_list));
                }
            }
        }
        prompt.push_str("<|im_end|>\n");
    }
    prompt.push_str("<|im_start|>assistant\n");
    prompt
}

/// Token usage metrics for a completion request.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Usage {
    /// Tokens processed in prompt/prefill.
    pub prompt_tokens: usize,
    /// Tokens generated by the model.
    pub completion_tokens: usize,
    /// Total tokens evaluated.
    pub total_tokens: usize,
}

/// Choice entry in non-streaming chat completion response.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChatChoice {
    /// Index of this choice in response list.
    pub index: usize,
    /// Generated assistant message.
    pub message: ChatMessage,
    /// Reason why completion stopped (e.g. "stop", "length").
    pub finish_reason: Option<String>,
}

/// Response returned by non-streaming `POST /v1/chat/completions`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChatCompletionResponse {
    /// Unique completion identifier.
    pub id: String,
    /// Object kind, fixed to "chat.completion".
    pub object: String,
    /// Unix timestamp when completion was generated.
    pub created: u64,
    /// Model name used for generation.
    pub model: String,
    /// Generated choices.
    pub choices: Vec<ChatChoice>,
    /// Token usage statistics.
    pub usage: Usage,
}

/// Delta payload for SSE streaming chunks.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChatDelta {
    /// Role update in chunk (usually present in the first chunk).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub role: Option<String>,
    /// Incremental content piece.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub content: Option<String>,
}

/// Choice entry in SSE streaming chunk.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChatChunkChoice {
    /// Index of choice.
    pub index: usize,
    /// Partial delta.
    pub delta: ChatDelta,
    /// Termination reason (only present on final chunk).
    pub finish_reason: Option<String>,
}

/// Chunk event emitted during streaming chat completions.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChatCompletionChunk {
    /// Unique chunk identifier.
    pub id: String,
    /// Object kind, fixed to "chat.completion.chunk".
    pub object: String,
    /// Unix timestamp.
    pub created: u64,
    /// Model name.
    pub model: String,
    /// Choices deltas list.
    pub choices: Vec<ChatChunkChoice>,
}

/// Aggregated session tiering statistics.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SessionStats {
    /// Number of hot sessions resident in memory.
    pub hot_sessions: usize,
    /// Total sessions across hot and cold tiers.
    pub total_sessions: usize,
    /// Hot cache configured capacity.
    pub hot_capacity: usize,
}

/// Response returned by `GET /kestrel/sessions`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SessionsListResponse {
    /// Metadata for all known sessions.
    pub sessions: Vec<SessionMetadata>,
    /// Overall session tiering statistics.
    pub stats: SessionStats,
}

/// Response returned by `DELETE /kestrel/sessions/:id`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DeleteSessionResponse {
    /// Session identifier.
    pub id: String,
    /// Whether session was deleted.
    pub deleted: bool,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_format_chatml_prompt() {
        let messages = vec![
            ChatMessage::new("system", "You are helpful."),
            ChatMessage::new("user", "Hello!"),
        ];

        let prompt = format_chatml_prompt(&messages);
        let expected = "<|im_start|>system\nYou are helpful.<|im_end|>\n<|im_start|>user\nHello!<|im_end|>\n<|im_start|>assistant\n";
        assert_eq!(prompt, expected);
    }
}
